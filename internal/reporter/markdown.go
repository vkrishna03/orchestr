package reporter

import (
	"fmt"
	"io"
	"strings"
	"time"

	"github.com/vkrishna03/orchestr/internal/executor"
	"github.com/vkrishna03/orchestr/internal/models"
)

// MarkdownReporter outputs results as Markdown.
type MarkdownReporter struct{}

// Report writes Markdown output.
func (r *MarkdownReporter) Report(w io.Writer, results []executor.TestResult, summary executor.Summary, service *models.Service) error {
	// Header
	fmt.Fprintln(w, "# Orchestr Test Report")
	fmt.Fprintln(w)
	fmt.Fprintf(w, "**Generated:** %s\n\n", time.Now().Format("2006-01-02 15:04:05"))

	// Service info
	if service != nil {
		fmt.Fprintln(w, "## Service")
		fmt.Fprintln(w)
		fmt.Fprintf(w, "| Property | Value |\n")
		fmt.Fprintf(w, "|----------|-------|\n")
		fmt.Fprintf(w, "| Name | %s |\n", service.Name)
		fmt.Fprintf(w, "| Type | %s |\n", service.Type)
		fmt.Fprintf(w, "| Port | %d |\n", service.Port)
		if profile := service.Config["profile"]; profile != "" {
			fmt.Fprintf(w, "| Profile | %s |\n", profile)
		}
		fmt.Fprintln(w)
	}

	// Summary
	fmt.Fprintln(w, "## Summary")
	fmt.Fprintln(w)
	passRate := calculatePassRate(summary)
	statusEmoji := "✅"
	if summary.Failed > 0 {
		statusEmoji = "❌"
	}

	fmt.Fprintf(w, "%s **%d/%d passed (%d%%)** in %s\n\n",
		statusEmoji, summary.Passed, summary.Total, passRate, formatDuration(summary.Duration))

	fmt.Fprintf(w, "| Metric | Value |\n")
	fmt.Fprintf(w, "|--------|-------|\n")
	fmt.Fprintf(w, "| Total | %d |\n", summary.Total)
	fmt.Fprintf(w, "| Passed | %d |\n", summary.Passed)
	fmt.Fprintf(w, "| Failed | %d |\n", summary.Failed)
	fmt.Fprintf(w, "| Duration | %s |\n", formatDuration(summary.Duration))
	fmt.Fprintln(w)

	// Results table
	fmt.Fprintln(w, "## Results")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "| Status | Entity | Method | Endpoint | Expected | Duration |")
	fmt.Fprintln(w, "|--------|--------|--------|----------|----------|----------|")

	for _, result := range results {
		entity := result.Spec.Entity
		if entity == "" {
			entity = "Test"
		}

		status := "✅"
		if !result.Passed {
			status = "❌"
		}

		fmt.Fprintf(w, "| %s | %s | %s | `%s` | %d | %s |\n",
			status,
			entity,
			result.Spec.Method,
			result.Spec.Endpoint,
			result.Spec.Expect.Status,
			formatDuration(result.Duration),
		)
	}
	fmt.Fprintln(w)

	// Failures section
	failures := getFailures(results)
	if len(failures) > 0 {
		fmt.Fprintln(w, "## Failures")
		fmt.Fprintln(w)

		for i, result := range failures {
			entity := result.Spec.Entity
			if entity == "" {
				entity = "Test"
			}

			fmt.Fprintf(w, "### %d. [%s] %s %s\n\n",
				i+1, entity, result.Spec.Method, result.Spec.Endpoint)

			fmt.Fprintf(w, "**Error:** %s\n\n", result.Error)

			// Request details
			fmt.Fprintln(w, "<details>")
			fmt.Fprintln(w, "<summary>Request Details</summary>")
			fmt.Fprintln(w)
			fmt.Fprintf(w, "- **URL:** `%s`\n", result.Request.URL)
			fmt.Fprintf(w, "- **Method:** %s\n", result.Request.Method)
			if len(result.Request.Headers) > 0 {
				fmt.Fprintln(w, "- **Headers:**")
				for k, v := range result.Request.Headers {
					// Mask auth tokens
					if strings.ToLower(k) == "authorization" && len(v) > 20 {
						v = v[:20] + "..."
					}
					fmt.Fprintf(w, "  - `%s`: `%s`\n", k, v)
				}
			}
			if result.Request.Body != "" {
				fmt.Fprintln(w, "- **Body:**")
				fmt.Fprintf(w, "  ```json\n  %s\n  ```\n", result.Request.Body)
			}
			fmt.Fprintln(w, "</details>")
			fmt.Fprintln(w)

			// Response details
			fmt.Fprintln(w, "<details>")
			fmt.Fprintln(w, "<summary>Response Details</summary>")
			fmt.Fprintln(w)
			fmt.Fprintf(w, "- **Status:** %d\n", result.Response.StatusCode)
			if result.Response.Body != "" {
				body := result.Response.Body
				if len(body) > 500 {
					body = body[:500] + "..."
				}
				fmt.Fprintln(w, "- **Body:**")
				fmt.Fprintf(w, "  ```json\n  %s\n  ```\n", body)
			}
			fmt.Fprintln(w, "</details>")
			fmt.Fprintln(w)
		}
	}

	// Footer
	fmt.Fprintln(w, "---")
	fmt.Fprintln(w, "*Generated by [Orchestr](https://github.com/vkrishna03/orchestr)*")

	return nil
}

// getFailures filters results to only failures.
func getFailures(results []executor.TestResult) []executor.TestResult {
	var failures []executor.TestResult
	for _, r := range results {
		if !r.Passed {
			failures = append(failures, r)
		}
	}
	return failures
}
